/**
 * Build the self-contained bundle of each skill's CLI, committed at
 * skills/<name>/scripts/<name>.mjs. Every dependency is inlined, so it runs
 * under plain `node` >= 20 on a machine that only has the skill installed.
 *
 *   bun scripts/build-cli.ts            # write the bundles
 *   bun scripts/build-cli.ts --check    # fail if a committed bundle is stale
 *
 * The version is injected from `git describe`. Committing the bundle changes
 * the sha (and CI may lack tags), so --check normalizes the embedded version
 * out of both sides before comparing: version drift never fails the check,
 * any real source change does.
 */
import * as esbuild from "esbuild";
import { chmodSync, existsSync, readFileSync } from "node:fs";
import { execSync } from "node:child_process";

interface Target {
  entry: string;
  outfile: string;
  define: string;
}

const TARGETS: Target[] = [
  {
    entry: "src/opsbot-core/bin.ts",
    outfile: "skills/opsbot-core/scripts/opsbot-core.mjs",
    define: "__OPSBOT_CORE_VERSION__",
  },
];

const check = process.argv.includes("--check");

function gitVersion(): string {
  try {
    return execSync("git describe --tags --always", { encoding: "utf8" }).trim() || "dev";
  } catch {
    return "dev";
  }
}

/** Matches the compiled `typeof X === "string" ? "<version>" : "dev"` literal. */
function normalizeVersion(source: string): string {
  return source.replace(/"[^"]*" : "dev"/, '"__VERSION__" : "dev"');
}

let stale = false;
for (const t of TARGETS) {
  const result = await esbuild.build({
    entryPoints: [t.entry],
    outfile: t.outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    legalComments: "none",
    define: { [t.define]: JSON.stringify(gitVersion()) },
    banner: {
      js: `#!/usr/bin/env node\n// GENERATED by scripts/build-cli.ts from ${t.entry.replace(/\/[^/]+$/, "/")} — do not edit. Run \`bun run build\`.`,
    },
    write: !check,
  });
  if (check) {
    const generated = result.outputFiles![0]!.text;
    const committed = existsSync(t.outfile) ? readFileSync(t.outfile, "utf8") : "";
    if (normalizeVersion(generated) !== normalizeVersion(committed)) {
      console.error(`${t.outfile} is out of date — run \`bun run build\` and commit the result`);
      stale = true;
    } else {
      console.log(`${t.outfile} is up to date`);
    }
  } else {
    chmodSync(t.outfile, 0o755);
    console.log(`Wrote ${t.outfile}`);
  }
}
if (stale) process.exit(1);
